@app.route("/api/drift/check", methods=["POST"])
def drift_check():
    job_id = request.form.get("job_id")
    if not job_id or job_id not in JOBS or not JOBS[job_id].get("orchestrator"):
        return jsonify({"error": "Active reference pipeline job required."}), 400

    if "file" not in request.files:
        return jsonify({"error": "New CSV file required for drift check."}), 400

    f = request.files["file"]
    try:
        new_df = pd.read_csv(f)
    except Exception as e:
        return jsonify({"error": f"Failed to parse new CSV: {e}"}), 400

    orch = JOBS[job_id]["orchestrator"]
    target_col = JOBS[job_id]["target_col"]
    drift_result = orch.drift_detector.run(
        orch.reference_df,
        new_df,
        target_col=target_col,
    )
    # Cache new_df in job for potential retraining
    JOBS[job_id]["last_drift_df"] = new_df

    return jsonify(_sanitize_json(drift_result))


@app.route("/api/drift/retrain", methods=["POST"])
def drift_retrain():
    data = request.get_json(force=True)
    job_id = data.get("job_id")

    if not job_id or job_id not in JOBS or not JOBS[job_id].get("orchestrator"):
        return jsonify({"error": "Job not found."}), 404

    job = JOBS[job_id]
    orch = job["orchestrator"]
    new_df = job.get("last_drift_df")
    if new_df is None:
        return jsonify({"error": "No drifted data uploaded yet. Run drift check first."}), 400

    target_col = job["target_col"]
    models = orch.registry.list_models()
    if not models:
        return jsonify({"error": "No registered base model found for retraining comparison."}), 400

    old_metadata = models[-1]
    retrain_res = orch.drift_detector.retrain(
        new_df=new_df,
        reference_df=orch.reference_df,
        target_col=target_col,
        old_metadata=old_metadata,
        registry=orch.registry,
    )
    return jsonify(_sanitize_json(retrain_res))


