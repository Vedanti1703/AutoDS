@app.route("/api/upload", methods=["POST"])
def upload():
    if "file" not in request.files:
        return jsonify({"error": "No file provided"}), 400
    f = request.files["file"]
    if not f.filename.lower().endswith(".csv"):
        return jsonify({"error": "Please upload a .csv file"}), 400

    job_id = uuid.uuid4().hex[:12]
    path = os.path.join(UPLOAD_DIR, f"{job_id}.csv")
    f.save(path)

    try:
        df = pd.read_csv(path)
    except Exception as e:
        return jsonify({"error": f"Could not parse CSV: {e}"}), 400

    if df.shape[0] < 10 or df.shape[1] < 2:
        return jsonify({"error": "Dataset needs at least 10 rows and 2 columns."}), 400

    size_mb = df.memory_usage(deep=True).sum() / (1024 ** 2)
    preview = df.head(10).astype(object).where(pd.notnull(df.head(10)), None).to_dict(orient="records")

    return jsonify(_sanitize_json({
        "job_id": job_id,
        "columns": list(df.columns),
        "n_rows": int(df.shape[0]),
        "n_cols": int(df.shape[1]),
        "size_mb": round(size_mb, 3),
        "preview": preview,
        "filename": f.filename,
    }))


