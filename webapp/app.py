def _sanitize_json(obj: Any) -> Any:
    """Recursively clean NaN, infinity, and numpy types for safe JSON serialization."""
    if isinstance(obj, dict):
        return {k: _sanitize_json(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_sanitize_json(v) for v in obj]
    if isinstance(obj, tuple):
        return [_sanitize_json(v) for v in obj]
    if isinstance(obj, (np.integer, int)):
        return int(obj)
    if isinstance(obj, (np.floating, float)):
        if math.isnan(obj) or math.isinf(obj):
            return None
        return float(round(obj, 6))
    if isinstance(obj, (np.bool_, bool)):
        return bool(obj)
    if isinstance(obj, np.ndarray):
        return _sanitize_json(obj.tolist())
    return obj


def _to_web_url(path: str) -> str:
    """Convert an absolute or relative filesystem plot path to a web URL."""
    if not path:
        return ""
    norm = os.path.normpath(path).replace("\\", "/")
    if "outputs/" in norm:
        rel = norm.split("outputs/", 1)[1]
        return f"/outputs/{rel}"
    return path


def _stage_key(raw_stage: str) -> str:
    """Map raw agent stage name to standardized UI stage identifier."""
    s = raw_stage.split("[")[0].strip()
    mapping = {
        "Profiler": "profile",
        "AutoEDA": "eda",
        "Preprocessing": "preprocess",
        "AnomalyDetection": "anomaly",
        "FeatureEngineering": "feature_eng",
        "FeatureSelection": "feature_sel",
        "ImbalanceHandling": "imbalance",
        "ModelSelection": "model_select",
        "Tuning": "tuning",
        "Evaluation": "evaluation",
        "Explainability": "explain",
        "ArtifactExport": "export",
        "Reporting": "report",
        "WhatIf": "whatif",
        "Assistant": "assistant",
        "ModelRegistry": "registry",
        "DriftDetection": "drift",
    }
    return mapping.get(s, s.lower())


