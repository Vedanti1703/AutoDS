@app.route("/download/<job_id>/csv/<filename>")
@app.route("/api/download/<job_id>/csv/<filename>")
def download_csv(job_id, filename):
    """Safely download an individual structured CSV result file for the given run."""
    # Sanitize filename and prevent path traversal
    safe_filename = os.path.basename(filename)
    if safe_filename != filename or safe_filename not in ALLOWED_CSV_FILENAMES:
        return jsonify({"error": "Invalid or unauthorized CSV file request."}), 400

    csv_dir = os.path.join(OUTPUTS_DIR, job_id, "csv")
    file_path = os.path.join(csv_dir, safe_filename)
    if not os.path.exists(file_path):
        return jsonify({"error": f"CSV file '{safe_filename}' not found for run '{job_id}'."}), 404

    return send_from_directory(
        csv_dir,
        safe_filename,
        as_attachment=True,
        download_name=f"{os.path.splitext(safe_filename)[0]}_{job_id}.csv",
        mimetype="text/csv",
    )


@app.route("/download/<job_id>/csv/all")
@app.route("/api/download/<job_id>/csv/all")
def download_all_csvs(job_id):
    """Download a ZIP archive containing all generated CSV result files for this run."""
    zip_filename = f"autods_{job_id}_csv_results.zip"
    zip_path = os.path.join(OUTPUTS_DIR, job_id, zip_filename)

    # If ZIP does not exist yet, build it using CSVExportManager
    if not os.path.exists(zip_path):
        csv_dir = os.path.join(OUTPUTS_DIR, job_id, "csv")
        if not os.path.exists(csv_dir):
            return jsonify({"error": f"No CSV results directory found for run '{job_id}'."}), 404
        mgr = CSVExportManager(output_root=OUTPUTS_DIR)
        zip_path = mgr.create_zip(job_id)

    if not os.path.exists(zip_path):
        return jsonify({"error": f"Could not create ZIP archive for run '{job_id}'."}), 404

    return send_from_directory(
        os.path.join(OUTPUTS_DIR, job_id),
        zip_filename,
        as_attachment=True,
        download_name=zip_filename,
        mimetype="application/zip",
    )


